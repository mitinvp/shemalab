const bar = (s: string) => `${s}\u0305`;
const bin = (n: number, w: number) => n.toString(2).padStart(w, "0");
const rngFor = (seed: string, id: string): Rng => mulberry32(hashSeed(`${seed.toLowerCase()}|${id}`));
const num = (x: number, d = 2) => String(Number(x.toFixed(d))).replace(".", ",");

function sample<T>(rng: Rng, arr: readonly T[], k: number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a.slice(0, k);
}

// ── Лабораторна 1: логічні елементи ────────────────────────────────────────
const GATE_FN: Record<string, (a: number, b: number) => number> = {
  AND: (a, b) => a & b,
  OR: (a, b) => a | b,
  NAND: (a, b) => 1 - (a & b),
  NOR: (a, b) => 1 - (a | b),
  XOR: (a, b) => a ^ b,
  XNOR: (a, b) => 1 - (a ^ b),
};

const FUNCS: { s: string; f: (a: number, b: number, c: number) => boolean }[] = [
  { s: `A·${bar("B")} + ${bar("A")}·C`, f: (a, b, c) => (a && !b) || (!a && c) ? true : false },
  { s: `(A + B)·${bar("C")} + B·C`, f: (a, b, c) => ((a || b) && !c) || (b && c) ? true : false },
  { s: "A·B + B·C + A·C", f: (a, b, c) => a + b + c >= 2 },
  { s: "(A ⊕ B)·C", f: (a, b, c) => a !== b && c === 1 },
  { s: `${bar("A")}·${bar("B")} + C`, f: (a, b, c) => (!a && !b) || c === 1 ? true : false },
  { s: `A·(B + ${bar("C")})`, f: (a, b, c) => a === 1 && (b === 1 || c === 0) },
  { s: `(A + ${bar("B")})·(B + C)`, f: (a, b, c) => (a || !b) && (b || c) ? true : false },
  { s: "A ⊕ B ⊕ C", f: (a, b, c) => (a ^ b ^ c) === 1 },
];

function minterms(f: (a: number, b: number, c: number) => boolean): number[] {
  const out: number[] = [];
  for (let m = 0; m < 8; m++) if (f((m >> 2) & 1, (m >> 1) & 1, m & 1)) out.push(m);
  return out;
}

function lab1(seed: string): LabVariant {
  const rng = rngFor(seed, "lr1");
  const gates = sample(rng, Object.keys(GATE_FN), 2);
  const fn = pick(rng, FUNCS);
  const ms = minterms(fn.f);
  return {
    task: [
      `Елементи для дослідження: ${gates[0]} та ${gates[1]}. Складіть їхні таблиці істинності за допомогою макета.`,
      `Функція: F(A, B, C) = ${fn.s}.`,
      "Складіть таблицю істинності F (8 рядків), запишіть ДДНФ.",
      "Реалізуйте F лише на елементах 2І-НЕ, накресліть схему й перевірте всі 8 наборів.",
    ],
    check: [
      ...gates.map((g) => `${g}: для наборів AB = 00, 01, 10, 11 вихід = ${[[0, 0], [0, 1], [1, 0], [1, 1]].map(([a, b]) => GATE_FN[g]!(a!, b!)).join(" ")}`),
      `F = Σm(${ms.join(", ")}); одиниць у стовпці F: ${ms.length} з 8.`,
    ],
  };
}

// ── Лабораторна 2: тригери ─────────────────────────────────────────────────
function lab2(seed: string): LabVariant {
  const rng = rngFor(seed, "lr2");
  const n = 6;
  const jk = Array.from({ length: n }, () => [rng() < 0.5 ? 0 : 1, rng() < 0.5 ? 0 : 1] as const);
  const d = Array.from({ length: n }, () => (rng() < 0.5 ? 0 : 1));
  const t = Array.from({ length: n }, () => (rng() < 0.5 ? 0 : 1));
  let q = 0;
  const qjk = jk.map(([j, k]) => {
    q = j === 0 && k === 0 ? q : j === 0 && k === 1 ? 0 : j === 1 && k === 0 ? 1 : 1 - q;
    return q;
  });
  const qd = d;
  q = 0;
  const qt = t.map((x) => (q = q ^ x));
  return {
    task: [
      "Початковий стан усіх тригерів Q = 0. Запис відбувається по фронту CLK; подайте 6 тактів.",
      `JK-тригер, пари (J K) на тактах 1–6: ${jk.map(([j, k]) => `${j}${k}`).join(", ")}.`,
      `D-тригер, значення D на тактах 1–6: ${d.join(", ")}.`,
      `T-тригер, значення T на тактах 1–6: ${t.join(", ")}.`,
      "Передбачте Q після кожного такту, перевірте у макеті й накресліть часові діаграми.",
    ],
    check: [`JK: Q = ${qjk.join(", ")}`, `D: Q = ${qd.join(", ")}`, `T: Q = ${qt.join(", ")}`],
  };
}

// ── Лабораторна 3: двійкові лічильники ──────────────────────────────────────
